#!/usr/bin/env python3
"""The baseline NRO of a performance comparison (docs/perf-test.md, perf_test.py compare-to): main or the last
published tag, built in a worktree of its own under build/perf/ so the contributor's checkout is not touched.

- A tag without the bench command (v0.4.7) gets it from tools/switch/perf_baselines/<tag>.patch.
- The worktree's build/gen is generated by the baseline's own tools/recomp from the contributor's cking.rpx and
  kept by the git tree hash of that tools/recomp (the recompiler changes between releases), linked into the
  worktree (build.sh mounts a linked build/gen into the container).
- The NRO is kept as build/perf/nro/<commit>.nro (<commit>-bench.nro when patched) and reused.
macOS and Linux with the container build only (podman or docker).
"""
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PATCHES = REPO / "tools" / "switch" / "perf_baselines"
BENCH_SOURCE = "runtime/src/platform/bench_switch.cpp"
WORK = REPO / "build" / "perf"
# where a cking.rpx usually is when neither --rpx nor WWHD_RPX says (README, docs/switch-port.md)
RPX_GLOBS = ["game/code/cking.rpx", "Rom/Decrypted/*/code/cking.rpx"]


def log(msg):
    print(msg, flush=True)


def git(repo, *args, check=True):
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if check and r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout.strip() if r.returncode == 0 else None


def fetch(repo):
    log("fetching origin (main and the tags)")
    git(repo, "fetch", "--quiet", "--tags", "origin")


def resolve(repo, which):
    """(name, commit) of a baseline: 'main' = origin/main, 'last-tag' = the newest tag on origin/main, else a tag
    or commit"""
    if which == "main":
        return "main", git(repo, "rev-parse", "origin/main^{commit}")
    if which == "last-tag":
        tag = git(repo, "describe", "--tags", "--abbrev=0", "origin/main", check=False)
        if not tag:
            raise SystemExit("no tag on origin/main")
        return tag, git(repo, "rev-parse", f"{tag}^{{commit}}")
    commit = git(repo, "rev-parse", "--verify", "--quiet", f"{which}^{{commit}}", check=False)
    if not commit:
        raise SystemExit(f"no such baseline: {which} (main, last-tag, a tag or a commit)")
    return which, commit


def has_bench(repo, commit):
    return git(repo, "cat-file", "-e", f"{commit}:{BENCH_SOURCE}", check=False) is not None


def bench_patch(repo, name, commit, patches=PATCHES):
    """None when the commit has the bench command, else the patch that adds it (SystemExit when there is none)"""
    if has_bench(repo, commit):
        return None
    p = Path(patches) / f"{name}.patch"
    if not p.exists():
        raise SystemExit(f"{name} has no bench command and there is no {p.relative_to(REPO) if p.is_relative_to(REPO) else p}"
                         " (only main and the last published tag can be measured)")
    return p


def recomp_key(repo, commit):
    return git(repo, "rev-parse", f"{commit}:tools/recomp")


def find_rpx(rpx=None):
    for c in [rpx, os.environ.get("WWHD_RPX")]:
        if c:
            if not Path(c).is_file():
                raise SystemExit(f"no such file: {c}")
            return Path(c).resolve()
    hits = [p for g in RPX_GLOBS for p in sorted(REPO.glob(g))]
    if len(hits) == 1:
        return hits[0].resolve()
    if hits:  # e.g. a USA and an EUR dump: the wrong one would build a baseline that cannot run
        raise SystemExit("more than one cking.rpx (" + ", ".join(str(h.relative_to(REPO)) for h in hits) +
                         "): give the USA one with --rpx PATH (or WWHD_RPX)")
    raise SystemExit("the baseline needs its own generated code: give your cking.rpx with --rpx PATH (or WWHD_RPX)")


def worktree(repo, commit, patch):
    wt = WORK / "worktrees" / (commit[:12] + ("-bench" if patch else ""))
    if (wt / ".git").exists():
        if git(wt, "rev-parse", "HEAD") != commit:
            raise SystemExit(f"{wt} is not at {commit[:12]}: remove it (git worktree remove --force {wt})")
        return wt
    wt.parent.mkdir(parents=True, exist_ok=True)
    log(f"worktree {wt.relative_to(REPO)} at {commit[:12]}")
    git(repo, "worktree", "add", "--detach", "--quiet", str(wt), commit)
    if patch:
        log(f"adding the bench command: {patch.relative_to(REPO)}")
        r = subprocess.run(["git", "-C", str(wt), "apply", str(patch)], capture_output=True, text=True)
        if r.returncode != 0:
            shutil.rmtree(wt, ignore_errors=True)
            git(repo, "worktree", "prune")
            raise SystemExit(f"{patch.name} does not apply: {r.stderr.strip()}")
    return wt


def ensure_gen(repo, wt, commit, rpx):
    gen = WORK / "gen" / recomp_key(repo, commit)
    if not any(gen.glob("code_*.c")):
        rpx = find_rpx(rpx)
        log(f"generating the baseline's code with its own recompiler into {gen.relative_to(REPO)} (a few minutes)")
        tmp = gen.with_name(gen.name + ".tmp")
        shutil.rmtree(tmp, ignore_errors=True)
        subprocess.run([sys.executable, "tools/recomp/recomp.py", str(rpx), str(tmp)], cwd=wt, check=True)
        shutil.rmtree(gen, ignore_errors=True)
        tmp.rename(gen)
    link = wt / "build" / "gen"
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink() or link.exists():
        if link.is_symlink() and Path(os.readlink(link)) == gen:
            return
        if link.is_symlink():
            link.unlink()
        else:
            shutil.rmtree(link)
    link.symlink_to(gen)


def build(repo, which, rpx=None):
    """the baseline NRO's path and its name (main / the tag), built when it is not kept yet"""
    name, commit = resolve(repo, which)
    patch = bench_patch(repo, name, commit)
    nro = WORK / "nro" / f"{commit[:12]}{'-bench' if patch else ''}.nro"
    if nro.exists():
        log(f"baseline {name} ({commit[:12]}): {nro.relative_to(REPO)}")
        return nro, name
    wt = worktree(repo, commit, patch)
    ensure_gen(repo, wt, commit, rpx)
    log(f"building the baseline {name} ({commit[:12]}) in {wt.relative_to(REPO)} (the first time: a full build)")
    subprocess.run(["tools/switch/build.sh"], cwd=wt, check=True)
    nro.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(wt / "build" / "switch-dk" / "wwhd.nro", nro)
    log(f"baseline {name}: {nro.relative_to(REPO)}")
    return nro, name
