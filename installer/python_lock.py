#!/usr/bin/env python3
"""Writes installer/shared/PythonLock.cs: the installers' pinned Python packages, each at one version with the
SHA-256 of every wheel the installers' Python (python-build-standalone 3.14, PythonLock.cs) can use on Windows,
macOS and Linux (x64 and arm64). pip then runs with --require-hashes --only-binary :all:, so it installs exactly
these files and never builds anything (docs/pinned-toolchain-plan.md, step 2).

usage: python3 installer/python_lock.py      (reads PyPI; a new pin is a reviewed change of PACKAGES below)
"""
import json
import os
import re
import sys
import urllib.request

# package -> version; the installers pick the ones they need (Pillow: icons; cmake, ninja: the desktop build)
PACKAGES = {
    "zstandard": "0.25.0",
    "pycryptodome": "3.23.0",
    "pillow": "12.0.0",
    "cmake": "4.1.2",
    "ninja": "1.13.0",
}
PY_MINOR = 14
PLATFORMS = {  # a wheel's platform tag -> the installer platform it serves
    r"win_amd64": "win-x64",
    r"win_arm64": "win-arm64",
    r"macosx_\d+_\d+_(arm64|universal2)": "osx-arm64",
    r"macosx_\d+_\d+_(x86_64|universal2)": "osx-x64",
    r"(manylinux\w*|linux)_x86_64": "linux-x64",
    r"(manylinux\w*|linux)_aarch64": "linux-arm64",
}


def usable_python(tag, abi):
    """the wheel's python/abi tags fit CPython 3.14 (not the free-threaded build)"""
    if abi == "abi3":
        return any(re.fullmatch(r"cp3(\d+)", t) and int(t[3:]) <= PY_MINOR for t in tag.split("."))
    if abi == "none":
        return any(t in ("py3", "py2") or t == "py3%d" % PY_MINOR for t in tag.split("."))
    return tag == "cp3%d" % PY_MINOR and abi == "cp3%d" % PY_MINOR


def wheels(name, version):
    with urllib.request.urlopen("https://pypi.org/pypi/%s/%s/json" % (name, version)) as r:
        files = json.load(r)["urls"]
    out = {}
    for f in files:
        m = re.fullmatch(r"[^-]+-[^-]+(?:-\d[^-]*)?-([^-]+)-([^-]+)-([^-]+)\.whl", f["filename"])
        if not m or not usable_python(m.group(1), m.group(2)):
            continue
        for plat_tag in m.group(3).split("."):
            for pattern, plat in PLATFORMS.items():
                if re.fullmatch(pattern, plat_tag):
                    out.setdefault(plat, set()).add(f["digests"]["sha256"])
    return out


def main():
    lines = []
    for name, version in PACKAGES.items():
        found = wheels(name, version)
        missing = [p for p in sorted(set(PLATFORMS.values())) if p not in found]
        if missing:
            sys.exit("%s %s has no Python 3.%d wheel for %s" % (name, version, PY_MINOR, ", ".join(missing)))
        digests = sorted(set().union(*found.values()))
        lines.append('        ["%s"] = ("%s", new[] {\n%s }),' % (
            name, version, "\n".join('            "%s",' % d for d in digests)))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shared", "PythonLock.cs")
    with open(path, "w", newline="\n") as f:
        f.write("""// Generated by installer/python_lock.py; do not edit. The installers' Python packages: one version each and the
// SHA-256 of every wheel Python 3.%d can use on the installers' platforms (pip --require-hashes --only-binary :all:).
using System.Collections.Generic;

namespace SwitchWakerHD.Installer;

static class PythonLock
{
    public static readonly Dictionary<string, (string version, string[] sha256)> Packages = new()
    {
%s
    };
}
""" % (PY_MINOR, "\n".join(lines)))
    print("wrote", path)


if __name__ == "__main__":
    main()
